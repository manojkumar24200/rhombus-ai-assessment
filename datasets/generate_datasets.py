"""Generate the messy baseline CSV and every drifted variant.

Deterministic (fixed seed) so the files in this folder can be regenerated byte-for-byte:

    python datasets/generate_datasets.py
"""
import csv
import random
from datetime import date, timedelta
from pathlib import Path

HERE = Path(__file__).parent
SEED = 42

FIRST = ["Alice", "Bob", "Carla", "Deepak", "Elena", "Farid", "Grace", "Hiro", "Isla", "Jamal",
         "Kavya", "Liam", "Mei", "Noah", "Olga", "Priya", "Quinn", "Ravi", "Sofia", "Tariq"]
LAST = ["Smith", "Jones", "Garcia", "Patel", "Kim", "Nguyen", "Brown", "Muller", "Rossi", "Khan"]
COUNTRY_VARIANTS = {
    "United States": ["United States", "USA", "usa", "U.S.", " US "],
    "India": ["India", "india", "IN", "IND"],
    "United Kingdom": ["United Kingdom", "UK", "u.k.", "England"],
    "Germany": ["Germany", "germany", "DE"],
}
STATUS_VARIANTS = {"shipped": ["shipped", "Shipped", "SHIPPED", " shipped"],
                   "pending": ["pending", "Pending", "PENDING"],
                   "cancelled": ["cancelled", "Canceled", "CANCELLED"]}
PRODUCTS = [("Keyboard", 49.99), ("Mouse", 19.99), ("Monitor", 189.00), ("USB Cable", 7.50),
            ("Laptop Stand", 34.95), ("Webcam", 59.00), ("Headset", 79.90), ("Desk Lamp", 24.99)]

BASE_COLUMNS = ["order_id", "customer_name", "email", "country", "order_date",
                "product", "quantity", "price", "status"]


def fmt_date(d: date, rng: random.Random) -> str:
    """Mixed date formats; all are month-first (US) where ambiguous."""
    style = rng.choice(["iso", "us", "us", "text"])
    if style == "iso":
        return d.isoformat()
    if style == "us":
        return f"{d.month:02d}/{d.day:02d}/{d.year}"
    return d.strftime("%b %d %Y")  # e.g. "Mar 04 2024"


def build_clean_rows(rng: random.Random, n: int = 120):
    rows = []
    start = date(2024, 1, 1)
    for i in range(1, n + 1):
        first, last = rng.choice(FIRST), rng.choice(LAST)
        product, price = rng.choice(PRODUCTS)
        canonical_country = rng.choice(list(COUNTRY_VARIANTS))
        canonical_status = rng.choice(list(STATUS_VARIANTS))
        rows.append({
            "order_id": f"ORD-{1000 + i}",
            "customer_name": f"{first} {last}",
            "email": f"{first.lower()}.{last.lower()}{i}@example.com",
            "country": rng.choice(COUNTRY_VARIANTS[canonical_country]),
            "_date": start + timedelta(days=rng.randint(0, 270)),
            "product": product,
            "quantity": str(rng.randint(1, 5)),
            "price": f"{price:.2f}",
            "status": rng.choice(STATUS_VARIANTS[canonical_status]),
        })
    return rows


def inject_mess(rows, rng: random.Random):
    """Add missing values, invalid entries and duplicates. Mutates + returns rows."""
    # Missing values
    for idx in rng.sample(range(len(rows)), 10):
        rows[idx]["country"] = ""
    for idx in rng.sample(range(len(rows)), 6):
        rows[idx]["email"] = ""
    for idx in rng.sample(range(len(rows)), 4):
        rows[idx]["quantity"] = ""
    # Inconsistent formatting: whitespace / casing in names
    for idx in rng.sample(range(len(rows)), 8):
        rows[idx]["customer_name"] = "  " + rows[idx]["customer_name"].upper() + " "
    # Price formatting noise ("$49.99")
    for idx in rng.sample(range(len(rows)), 8):
        rows[idx]["price"] = "$" + rows[idx]["price"]
    # Invalid entries
    invalid = rng.sample(range(len(rows)), 10)
    rows[invalid[0]]["email"] = "not-an-email"
    rows[invalid[1]]["email"] = "bob@@example"
    rows[invalid[2]]["price"] = "-19.99"
    rows[invalid[3]]["price"] = "abc"
    rows[invalid[4]]["quantity"] = "-3"
    rows[invalid[5]]["quantity"] = "1000000"
    rows[invalid[6]]["_raw_date"] = "2024-13-45"
    rows[invalid[7]]["_raw_date"] = "not a date"
    rows[invalid[8]]["status"] = "???"
    rows[invalid[9]]["order_id"] = ""
    # Exact duplicates (8) and near-duplicates differing only in whitespace/case (4)
    dupes = [dict(r) for r in rng.sample(rows, 8)]
    near = []
    for r in rng.sample(rows, 4):
        r2 = dict(r)
        r2["customer_name"] = r2["customer_name"].strip().lower()
        near.append(r2)
    rows.extend(dupes + near)
    rng.shuffle(rows)
    return rows


def render(rows, rng: random.Random, date_fn=None):
    """Turn internal rows into CSV dicts with formatted dates."""
    out = []
    for r in rows:
        r = dict(r)
        if "_raw_date" in r:
            r["order_date"] = r.pop("_raw_date")
        elif date_fn:
            r["order_date"] = date_fn(r["_date"])
        else:
            r["order_date"] = fmt_date(r["_date"], rng)
        r.pop("_date", None)
        out.append(r)
    return out


def write(name, rows, columns):
    path = HERE / name
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=columns, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {path.name}: {len(rows)} rows, {len(columns)} cols")


def main():
    rng = random.Random(SEED)
    raw = inject_mess(build_clean_rows(rng), rng)
    # Fix the rendered date strings once so every variant shares identical values.
    date_rng = random.Random(SEED + 1)
    baseline = render(raw, date_rng)
    write("baseline.csv", baseline, BASE_COLUMNS)

    # ---- Schema drift: each change on its own ----
    write("schema_drop_column.csv", baseline, [c for c in BASE_COLUMNS if c != "email"])

    renamed = [{**r, "unit_price": r["price"]} for r in baseline]
    write("schema_rename_column.csv", renamed,
          [("unit_price" if c == "price" else c) for c in BASE_COLUMNS])

    words = {"1": "one", "2": "two", "3": "three", "4": "four", "5": "five"}
    retyped = [{**r, "quantity": words.get(r["quantity"], r["quantity"])} for r in baseline]
    write("schema_type_change.csv", retyped, BASE_COLUMNS)

    add_rng = random.Random(SEED + 2)
    added = [{**r, "discount_code": add_rng.choice(["", "SPRING10", "VIP20", "NONE"])} for r in baseline]
    write("schema_add_column.csv", added, BASE_COLUMNS + ["discount_code"])

    # ---- Schema drift: all four together ----
    combined = [{**r, "unit_price": r["price"],
                 "quantity": words.get(r["quantity"], r["quantity"]),
                 "discount_code": a["discount_code"]} for r, a in zip(baseline, added)]
    combined_cols = [("unit_price" if c == "price" else c) for c in BASE_COLUMNS if c != "email"]
    write("schema_combined.csv", combined, combined_cols + ["discount_code"])

    # ---- Semantic drift: same structure, different meaning ----
    def to_cents(v: str) -> str:
        try:
            neg = v.startswith("-")
            num = float(v.replace("$", "").replace("-", ""))
            return ("-" if neg else "") + ("$" if "$" in v else "") + str(int(round(num * 100)))
        except ValueError:
            return v
    write("semantic_price_cents.csv", [{**r, "price": to_cents(r["price"])} for r in baseline], BASE_COLUMNS)

    # Same dates as baseline, but ambiguous ones written day-first (DD/MM/YYYY).
    ddmm_rng = random.Random(SEED + 1)
    ddmm = render(raw, ddmm_rng)
    for r_out, r_base in zip(ddmm, baseline):
        v = r_base["order_date"]
        if len(v) == 10 and v[2] == "/" and v[5] == "/":
            mm, dd, yyyy = v.split("/")
            r_out["order_date"] = f"{dd}/{mm}/{yyyy}"
    write("semantic_date_ddmm.csv", ddmm, BASE_COLUMNS)


if __name__ == "__main__":
    main()
